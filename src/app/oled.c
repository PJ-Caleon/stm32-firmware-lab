static void oled_send_cmd(uint8_t cmd){
  uint8_t buf[2];
  buf[0] = 0x00;
  buf[1] = cmd;
  i2c_write(OLED_I2C_ADDR, buf, 2);
}

void oled_clear(void){
  memset(framebuffer, 0, sizeof(framebuffer));
}

void oled_draw_pixel(uint8_t x, uint8_t y, uint8_t color){
  if (x >= 128 || y >= 64) return;
    
  if (color) {
    framebuffer[x + (uint8_t)(y / 8) * 128] |= (1 << (y % 8));
  } else {
    framebuffer[x + (uint8_t)(y / 8) * 128] &= ~(1 << (y % 8));
  }
}

void oled_draw_char(uint8_t x, uint8_t y, char c){
  if (c < ' ' || c > 'Z') {
    c = ' ';
  }
  
  uint8_t index = c - ' ';

  for (uint8_t i = 0; i < 5; i++){
    uint8_t line = font5x7[index][i];
    for (uint8_t j = 0; j < 8; j++){ 
      if (line & (1 << j)){
        oled_draw_pixel(x + i, y + j, 1);
      } else {
        oled_draw_pixel(x + i, y + j, 0);
      }
    }
  }
}

void oled_draw_string(uint8_t x, uint8_t y, const char *str){
  while (*str){
    oled_draw_char(x,y,*str);
    x += 6;
    if (x > 122) break;
    str++;
  }
}

__attribute__((weak)) uint8_t chunk_packet[65];

void oled_refresh(void){
  oled_send_cmd(0x21);
  oled_send_cmd(0);
  oled_send_cmd(127);
  oled_send_cmd(0x22);
  oled_send_cmd(0);
  oled_send_cmd(7);

  chunk_packet[0] = 0x40;

  for(uint16_t i = 0; i < 1024; i += 64){
    for (uint16_t j = 0; j < 64; j++){
      chunk_packet[1 + j] = framebuffer[i + j];
    }
    i2c_write(OLED_I2C_ADDR, chunk_packet, 65);
  }
}

void oled_dashboard(uint32_t adc_val){
  static uint32_t counter = 0;
  static uint32_t high_adc_start_time = 0;
  static uint8_t show_pixel_art = 0;
  static uint8_t art_shown = 0;
  char buf[32];

  counter++;

  if (adc_val > 4000) {
    if (high_adc_start_time == 0) {
      high_adc_start_time = millis();
    } else if ((millis() - high_adc_start_time) >= 3000) {
      show_pixel_art = 1;
    }
  } else {
    high_adc_start_time = 0;
    show_pixel_art = 0;
  }

  if (show_pixel_art) {
    if (!art_shown) {
      draco_malfoid(); 
      art_shown = 1;
    }
  } else {
    art_shown = 0;

    oled_clear();
    oled_draw_string(0, 0, "DRACO MALFOID");

    sprintf(buf, "CNT: %" PRIu32, counter);
    oled_draw_string(0, 22, buf);

    sprintf(buf, "ADC: %" PRIu32, adc_val);
    oled_draw_string(0, 34, buf);

    oled_refresh();
  }
}

void oled_init(void){
  uint8_t init_sequence[] = {
    0x00, // Control byte: Command
    0xAE, // Display OFF (sleep mode)
    0xD5, 0x80, // Set Display Clock Divide Ratio / Oscillator Frequency
    0xA8, 0x3F, // Set Multiplex Ratio (1/64)
    0xD3, 0x00, // Set Display Offset
    0x40, // Set Display Start Line (0)
    0x8D, 0x14, // Enable Charge Pump Regulator
    0x20, 0x00, // Set Memory Addressing Mode (Horizontal Addressing Mode)
    0xA1, // Set Segment Re-map (Column 127 mapped to SEG0)
    0xC8, // Set COM Output Scan Direction (Reversed scan direction)
    0xDA, 0x12, // Set COM Pins Hardware Configuration
    0x81, 0xCF, // Set Contrast Control
    0xD9, 0xF1, // Set Pre-charge Period
    0xDB, 0x40, // Set VCOMH Deselect Level
    0xA4, // Entire Display On (Resume to RAM content display)
    0xA6, // Set Normal Display (Non-inverted)
    0xAF  // Display ON in normal mode
  };

  i2c_write(OLED_I2C_ADDR, init_sequence, sizeof(init_sequence));
  oled_clear();
  oled_refresh();
}
